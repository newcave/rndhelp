PREFIX = ["", "", "[과제] ", "(국가과제) ", "R&D-", "연구용 "]
SUFFIX = ["", "", " 1식", " 외", " (10월분)", " 건", " 대금"]


def make_train(n_per_template: int = 40) -> pd.DataFrame:
    rows = []
    for acc, bimok, semok, items, vendors, (lo, hi) in TEMPLATES:
        for _ in range(n_per_template):
            desc = f"{rng.choice(PREFIX)}{rng.choice(items)}{rng.choice(SUFFIX)}"
            rows.append({
                "account": acc,
                "description": desc.strip(),
                "vendor": rng.choice(vendors),
                "amount": int(rng.uniform(lo, hi) // 1000 * 1000),
                "rcms_bimok": bimok,
                "rcms_semok": semok,
            })
    rng.shuffle(rows)
    return pd.DataFrame(rows)


